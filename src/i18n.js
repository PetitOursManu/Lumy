export const BUILT_IN = { en, fr, es, de, it, pt }

/** The full string table for `lang`: built-in, then English, then the site's overrides. */
export function stringsFor(lang, overrides = {}) {
  return { ...en, ...(BUILT_IN[lang] || {}), ...(overrides[lang] || {}) }
}

/** Fill {placeholders} in a string. */
export function fill(template, values = {}) {
  return String(template).replace(/\{(\w+)\}/g, (m, k) => (k in values ? values[k] : m))
}

